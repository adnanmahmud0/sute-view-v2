#!/usr/bin/env bash
# ==============================================================================
# render-nginx.sh - Dynamic Nginx virtual host generator with blue/green upstreams
# ==============================================================================
set -euo pipefail

PROJECT_SLUG="${PROJECT_SLUG:-fullstack}"
DOMAIN="${DOMAIN:-example.com}"
API_SUBDOMAIN="${API_SUBDOMAIN:-api}"
ADMIN_SUBDOMAIN="${ADMIN_SUBDOMAIN:-admin}"

API_PORT="${API_PORT:-5000}"
ADMIN_PORT="${ADMIN_PORT:-3001}"
WEB_PORT="${WEB_PORT:-3000}"

HAS_WEB="${HAS_WEB:-true}"
HAS_ADMIN="${HAS_ADMIN:-true}"
HAS_API="${HAS_API:-true}"

UPSTREAMS_FILE="/etc/nginx/conf.d/${PROJECT_SLUG}-upstreams.conf"
SITE_CONF="/etc/nginx/sites-available/${PROJECT_SLUG}.conf"

echo "Generating Nginx upstreams at $UPSTREAMS_FILE..."
sudo tee "$UPSTREAMS_FILE" > /dev/null <<EOF
# Autogenerated blue/green upstreams for ${PROJECT_SLUG}
$([ "$HAS_API" = "true" ] && echo "upstream ${PROJECT_SLUG}_api_upstream { server 127.0.0.1:${API_PORT}; keepalive 32; }")
$([ "$HAS_ADMIN" = "true" ] && echo "upstream ${PROJECT_SLUG}_admin_upstream { server 127.0.0.1:${ADMIN_PORT}; keepalive 32; }")
$([ "$HAS_WEB" = "true" ] && echo "upstream ${PROJECT_SLUG}_web_upstream { server 127.0.0.1:${WEB_PORT}; keepalive 32; }")
EOF

echo "Generating Nginx virtual hosts at $SITE_CONF..."
sudo tee "$SITE_CONF" > /dev/null <<EOF
# ==============================================================================
# Virtual Host Configuration for ${PROJECT_SLUG} (${DOMAIN})
# ==============================================================================

$([ "$HAS_API" = "true" ] && cat <<API_BLOCK
# 1. API Backend (${API_SUBDOMAIN}.${DOMAIN})
server {
    listen 80;
    server_name ${API_SUBDOMAIN}.${DOMAIN};
    client_max_body_size 50M;

    location / {
        proxy_pass http://${PROJECT_SLUG}_api_upstream;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
        proxy_connect_timeout 60s;
        proxy_read_timeout 60s;
    }
}
API_BLOCK
)

$([ "$HAS_ADMIN" = "true" ] && cat <<ADMIN_BLOCK
# 2. Super Admin Portal (${ADMIN_SUBDOMAIN}.${DOMAIN})
server {
    listen 80;
    server_name ${ADMIN_SUBDOMAIN}.${DOMAIN};

    location / {
        proxy_pass http://${PROJECT_SLUG}_admin_upstream;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
ADMIN_BLOCK
)

$([ "$HAS_WEB" = "true" ] && cat <<WEB_BLOCK
# 3. Main Web Application (${DOMAIN} & www.${DOMAIN})
server {
    listen 80;
    server_name ${DOMAIN} www.${DOMAIN};

    location / {
        proxy_pass http://${PROJECT_SLUG}_web_upstream;
        proxy_http_version 1.1;
        proxy_set_header Upgrade \$http_upgrade;
        proxy_set_header Connection 'upgrade';
        proxy_set_header Host \$host;
        proxy_set_header X-Real-IP \$remote_addr;
        proxy_set_header X-Forwarded-For \$proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto \$scheme;
    }
}
WEB_BLOCK
)

$([ "$HAS_WEB" = "false" ] && [ "$HAS_ADMIN" = "true" ] && cat <<REDIRECT_BLOCK
# 3. Root Domain Redirect to Admin (${DOMAIN} -> ${ADMIN_SUBDOMAIN}.${DOMAIN})
server {
    listen 80;
    server_name ${DOMAIN} www.${DOMAIN};
    return 301 http://${ADMIN_SUBDOMAIN}.${DOMAIN}\$request_uri;
}
REDIRECT_BLOCK
)
EOF

# Enable site configuration symlink if not already enabled
if [ ! -f "/etc/nginx/sites-enabled/${PROJECT_SLUG}.conf" ]; then
  sudo ln -sf "$SITE_CONF" "/etc/nginx/sites-enabled/${PROJECT_SLUG}.conf"
fi

# Remove default site if present
if [ -f "/etc/nginx/sites-enabled/default" ]; then
  sudo rm -f "/etc/nginx/sites-enabled/default"
fi

echo "Validating Nginx configuration syntax..."
sudo nginx -t
echo "Reloading Nginx..."
sudo nginx -s reload
echo "Nginx virtual hosts successfully applied!"
